export const describePattern = (p: Pattern) => {
  const bits = [PATTERN_NAME()[p.type] ?? p.type];
  if (p.type === 'summon' && p.enemy) bits.push(tx(`${p.count ?? 1} 只${lnk.enemy(p.enemy)}`, `${p.count ?? 1}× ${lnk.enemy(p.enemy)}`));
  else if (p.count) bits.push(`×${p.count}`);
  if (p.debuff) bits.push(tx(`命中附带 ${stApply(p.debuff)}`, `inflicts ${stApply(p.debuff)}`));
  if (p.buff) bits.push(tx(`自身/同伴获得 ${stApply(p.buff)}`, `self/allies gain ${stApply(p.buff)}`));
  return `${bits.join(' ')}${tx(`（每 ${p.cd}s）`, ` (every ${p.cd}s)`)}`;
};
