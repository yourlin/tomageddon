export const navLine = (file: string) => docs().map(([n, f]) => (f === file ? `**${n}**` : `[${n}](${f})`)).join(' · ');
export const langLine = (file: string) => (lang === 'en' ? `[中文](../${file}) · **English**` : `**中文** · [English](en/${file})`);
export const generatedNote = () => tx('> 由 `npm run docs` 从 `src/data/*.ts` 自动生成，请勿手改。', '> Generated by `npm run docs` from `src/data/*.ts`. Do not edit by hand.');

export class Doc {
  private body: string[] = [];
  private toc: string[] = [];
  constructor(
    private file: string,
    private title: string,
    private intro: string[],
  ) {}
  h2(text: string, id: string) {
    this.toc.push(`- [${text}](#${id})`);
    this.body.push(`<a id="${id}"></a>`, '', `## ${text}`, '');
  }
  h3(text: string, id: string, inToc = true) {
    if (inToc) this.toc.push(`  - [${text}](#${id})`);
    this.body.push(`<a id="${id}"></a>`, '', `### ${text}`, '');
  }
  p(...lines: string[]) {
    this.body.push(...lines, '');
  }
  table(head: string[], rows: (string | number)[][]) {
    this.body.push(`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`);
    for (const r of rows) this.body.push(`| ${r.map((c) => String(c).replace(/\|/g, '\\|').replace(/\n/g, '<br>')).join(' | ')} |`);
    this.body.push('');
  }
  write() {
    const nav = navLine(this.file);
    const out = [`# ${this.title}`, '', langLine(this.file), '', nav, '', generatedNote(), '', ...this.intro, '', `## ${tx('目录', 'Contents')}`, '', ...this.toc, '', ...this.body, '---', '', nav, ''];
    mkdirSync(outDir(), { recursive: true });
    writeFileSync(`${outDir()}/${this.file}`, out.join('\n'));
  }
}

