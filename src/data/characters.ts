export type SkillType =
  'nova' | 'dash' | 'buff' | 'ring' | 'heal' | 'strikes' | 'ghost' | 'clone' | 'barrage' | 'missile' | 'screen' | 'field' | 'curse';

export interface SkillDef {
  name: string;
  desc: string;
  type: SkillType;
  cd: number;
  mult?: number; // 伤害系数：× 当前武器平均单次伤害
  radius?: number;
  count?: number;
  duration?: number;
  distance?: number;
  mods?: StatMods;
  status?: StatusApply[]; // 对命中敌人施加
  selfStatus?: StatusApply[]; // 对自己施加
  heal?: number;
  xp?: number; // 立即获得经验
  color: number;
}

export interface CharacterDef {
  id: string;
  name: string;
  title: string;
  desc: string;
  color: number;
  look: RigSpec;
  mods: StatMods;
  classMult?: Partial<Record<'melee' | 'ranged' | 'elemental', number>>;
  startWeapons: string[];
  traits: string[];
  maxWeapons?: number;
  dodgeCap?: number;
  shopDiscount?: number;
  levelUpChoices?: number;
  special?: ItemSpecial;
  skill: SkillDef;
  /** 解锁价格（成就点）；不填表示默认解锁 */
  cost?: number;
  /** 购买前需要先达成的成就（id 与最低等级，等级从 1 起） */
  requires?: { ach: string; tier: number };
}

const S = (id: StatusApply['id'], dur: number, stacks = 1, chance?: number): StatusApply => ({ id, dur, stacks, chance });

