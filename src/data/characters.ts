export type SkillType =
  'nova' | 'dash' | 'buff' | 'ring' | 'heal' | 'strikes' | 'ghost' | 'clone' | 'barrage' | 'missile' | 'screen' | 'field' | 'curse';

export interface SkillDef {
  name: string;
  desc: string;
  type: SkillType;
  cd: number;
  mult?: number; // 伤害系数：× 当前武器平均单次伤害
  radius?: number;
  count?: number;
  duration?: number;
  distance?: number;
  mods?: StatMods;
  status?: StatusApply[]; // 对命中敌人施加
  selfStatus?: StatusApply[]; // 对自己施加
  heal?: number;
  xp?: number; // 立即获得经验
  color: number;
}

export interface CharacterDef {
  id: string;
  name: string;
  title: string;
  desc: string;
  color: number;
  look: RigSpec;
  mods: StatMods;
  classMult?: Partial<Record<'melee' | 'ranged' | 'elemental', number>>;
  startWeapons: string[];
  /** 契合标签：带任意一个这些标签的武器都是契合武器，伤害 +10% 并获得契合特效（data/affinity.ts、data/weaponTags.ts），商店中更常出现 */
  favored: string[];
  traits: string[];
  /** 专属天赋（机制见 systems/Talents.ts；部分通过 special 实现） */
  talent: { name: string; desc: string };
  maxWeapons?: number;
  dodgeCap?: number;
  shopDiscount?: number;
  levelUpChoices?: number;
  special?: ItemSpecial;
  skill: SkillDef;
  /** 解锁条件：达成指定成就的指定等级（等级从 1 起）后自动解锁；不填表示默认解锁 */
  unlock?: { ach: string; tier: number };
}

const S = (id: StatusApply['id'], dur: number, stacks = 1, chance?: number): StatusApply => ({ id, dur, stacks, chance });

