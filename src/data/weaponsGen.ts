/** 由模板生成武器数据（模板必须是 weapons.ts 里的基础武器，见 buildGenWeapons） */
export function buildGenWeapons(byId: Record<string, WeaponDef>): WeaponDef[] {
  return GEN_SPECS.map((g) => {
    const t = byId[g.from];
    if (!t) throw new Error(`weaponsGen: 模板 ${g.from} 不存在`);
    const k = g.dmg ?? 1;
    const def: WeaponDef = {
      ...t,
      ...g.over,
      id: g.id,
      name: g.name,
      desc: g.desc,
      tags: g.tags,
      damage: t.damage.map((d) => Math.max(1, Math.round(d * k))),
      // 子弹 / 地雷 / 光环的外观沿用模板（见 WeaponDef.template），子弹按系列染色
      template: t.template ?? t.id,
      projTint: g.over?.projTint ?? g.tint,
      price: Math.round(t.price * (0.95 + 0.1 * k)),
      evolvedFrom: undefined,
    };
    return def;
  });
}

export const GEN_WEAPONS_EN: WeaponsEn = Object.fromEntries(GEN_SPECS.map((g) => [g.id, { name: g.en, desc: g.enDesc }]));

