/** 素材来源（文件名相对于条目目录） */
export type ArtSource =
  /** 单张透明图（PNG / WebP） */
  | { type: 'static'; file: string }
  /** 规则精灵表：等大帧按行排列；帧间留边防止采样串色 */
  | { type: 'spritesheet'; file: string; frameWidth: number; frameHeight: number; spacing?: number; margin?: number }
  /** 图集（TexturePacker JSON Hash / Array）：支持裁切（trimmed），不支持旋转打包 */
  | { type: 'atlas'; file: string; data: string };

/** 一个动作的帧序列 */
export interface ArtAnim {
  /** 精灵表帧号或图集帧名 */
  frames: (number | string)[];
  /** 帧率，默认 10 */
  fps?: number;
  /** 是否循环；默认 idle / move / stun / victory / frozen 循环，其余播一次 */
  loop?: boolean;
  /**
   * 一次性动作（attack / hurt / die / spawn / cast）的时长适配：
   * fit（默认）= 按玩法时长拉伸 / 压缩播放速度；hold = 按 fps 播放，提前播完停在末帧、来不及播完就被打断。
   * 无论哪种都不会延长玩法时长；windup / charge 由玩法决定持续多久，播完停在末帧（或设 loop）。
   */
  fit?: 'fit' | 'hold';
}

export interface EntityArtEntry {
  kind: VisualKind;
  /** 实体 id（characters / enemies / bosses 里的 id） */
  id: string;
  /** 只有角色有皮肤（skins.ts 的皮肤 id） */
  skinId?: string;
  variant?: 'champ';
  /** 素材资源版本：替换文件后 +1，用于缓存失效与问题定位 */
  version: number;
  /** 条目目录（相对 src/assets/entities），默认 <kind>/<id>[/<skinId>|/champ] */
  dir?: string;
  /** 战斗形象；不填表示只替换头像 */
  source?: ArtSource;
  /** 基准帧（静态展示、缺动作时使用）；默认第一帧 / idle 第一帧 */
  baseFrame?: number | string;
  /** 静态形象的闭眼帧，与原图共用画布、锚点和尺寸。 */
  blink?: string;
  /** 动作表；缺的动作用基准帧 + 通用反馈（呼吸、弹跳、闪白、旋转、淡出） */
  anims?: Partial<Record<RigState, ArtAnim>>;
  /** 地面接触点（0~1，相对单帧裁切前尺寸），所有帧共用同一参考点；默认 { x: 0.5, y: 0.95 } */
  anchor?: { x: number; y: number };
  /** 美术参考半径（源图像素）：显示缩放 = 玩法半径 / refRadius × displayScale；默认帧宽 × 0.4 */
  refRadius?: number;
  /** 额外显示倍率（默认 1），只影响画面，不影响碰撞 */
  displayScale?: number;
  /** 地面在实体中心下方多少个参考半径（与 Rig 的脚底一致），默认 0.9 */
  groundY?: number;
  /** 原始朝向：1 = 面朝右（默认）；移动动画统一朝右，-1 仅兼容尚未迁移的旧素材。 */
  facing?: 1 | -1;
  /** 是否允许左右镜像，默认 true；移动动画必须开启，非对称装备随整图一起翻转。 */
  mirror?: boolean;
  /** 脚下阴影宽度（相对玩法半径，默认 1.8；0 = 不画） */
  shadow?: number;
  /** 头像文件（相对条目目录，建议 256×256 透明 PNG）；不填时若目录里有 portrait.png 则自动使用 */
  portrait?: string;
  /**
   * 显式复用声明（只在基础条目上有效）：没声明就不复用，回退到对应皮肤 / 变体的程序化 Rig，
   * 不会用基础插画悄悄覆盖已购买的皮肤，也不会把词缀精英显示成普通怪物。
   */
  reuse?: {
    /** 可复用到哪些皮肤（可附带整体调色）；'all' = 全部皮肤原样复用 */
    skins?: 'all' | Record<string, { tint?: number }>;
    /** 词缀精英复用基础外观并加金色光环 */
    champ?: 'goldAura';
  };
  /** 制作来源 / 提示词出处，只用于交接与问题定位 */
  credit?: string;
}

export interface MapArtEntry {
  /** 章节 id */
  ch: number;
  version: number;
  /** 条目目录（相对 src/assets/maps），默认 ch<章> */
  dir?: string;
  /** 地面层：覆盖整张地图（含场外区域），不带角色 / 掉落 / 预警 */
  ground: string;
  /** 前景层（边缘装饰等），默认画在地面之上、所有实体之下；depth 可调但必须保证角色、掉落与预警清晰可见 */
  foreground?: { file: string; depth?: number; alpha?: number };
  /** 选关缩略图（小图，启动时加载）；不填时选关界面在地面层加载后用它裁切，否则用程序地图 */
  thumb?: string;
  /** 按章节加载的环境机关贴图；仅随 ground 请求加载，缩略图不依赖它们。 */
  objects?: Record<string, { file: string; width: number; height: number; fromWave?: number }>;
  /** 贴图对应的世界矩形（中心 + 尺寸），默认 mapPlacement：场地外接矩形每边外扩 MAP_MARGIN */
  world?: { x: number; y: number; w: number; h: number };
  credit?: string;
}

